import json
import logging
import random
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

import numpy as np
from PIL import Image

from data.base_dataset import BaseDataset
from data.dataset_util import depth_to_world_coords_points
from vggt.utils.geometry import closed_form_inverse_se3


class OV9DPoseNormalizeDataset(BaseDataset):
    """OV9D object-conditioned dataset with BOP GT pose normalization.

    This dataset reads OV9D ``oo3d9dsingle`` scenes through split manifests
    generated by ``ov9d/prepare_data.py``. It mirrors the output contract of
    ``SixDPoseNormalizeDataset``:

    - ``images``: randomly sampled scene RGB views
    - ``object_images``: independently sampled object RGB views with visible
      mask applied and background set to white
    - ``extrinsics``: scene camera extrinsics normalized to the first selected
      scene view
    - ``object_rotation/object_translation/object_srt``: object pose in the
      first selected scene camera coordinate system, with translation divided by
      the point-cloud average scale
    """

    DEFAULT_DATA_ROOT = "/mnt/train-data-4-hdd/yian/freepose/ov9d/ov9d"
    DEFAULT_NUM_SCENE_VIEWS = 4
    DEFAULT_NUM_OBJECT_VIEWS = 4

    def __init__(
        self,
        common_conf,
        split: str = "train",
        DATA_ROOT: str = DEFAULT_DATA_ROOT,
        SPLIT_JSON: Optional[str] = None,
        len_train: Optional[int] = None,
        len_test: Optional[int] = None,
        verify_files: bool = True,
        num_scene_views: int = DEFAULT_NUM_SCENE_VIEWS,
        num_object_views: int = DEFAULT_NUM_OBJECT_VIEWS,
        min_view_gap: int = 5,
        object_index: int = 0,
        load_point_map: bool = False,
        scale_by_points: bool = True,
        negative_object_prob: float = 0.0,
        only_scene_name: str = "",
        only_scene_names: Optional[List[str]] = None,
    ):
        super().__init__(common_conf=common_conf)

        self.debug = common_conf.debug
        self.training = common_conf.training
        self.inside_random = common_conf.inside_random

        self.split = str(split)
        self.data_root = Path(DATA_ROOT)
        self.single_root = self.data_root / "oo3d9dsingle"
        self.split_json = Path(SPLIT_JSON) if SPLIT_JSON else self.data_root / "splits" / f"{self.split}.json"

        self.verify_files = bool(verify_files)
        self.num_scene_views = int(num_scene_views)
        self.num_object_views = int(num_object_views)
        self.min_view_gap = int(min_view_gap)
        self.object_index = int(object_index)
        self.load_point_map = bool(load_point_map)
        self.scale_by_points = bool(scale_by_points)
        self.negative_object_prob = float(negative_object_prob)

        self.only_scene_names = [x.strip() for x in (only_scene_names or []) if str(x).strip()]
        if only_scene_name:
            self.only_scene_names = [only_scene_name.strip()]

        self.records = self._build_records()
        self.sequence_list_len = len(self.records)
        self.records_by_frame_num = {
            frame_num: list(range(self.sequence_list_len)) for frame_num in range(4, 7)
        }
        if self.sequence_list_len == 0:
            raise RuntimeError(
                "No valid OV9D normalized pose samples found. "
                f"Checked split_json={self.split_json}, single_root={self.single_root}"
            )

        if self.split == "train":
            self.len_train = int(len_train) if len_train is not None else self.sequence_list_len
        elif self.split in {"test", "val", "test1", "test2"}:
            self.len_train = int(len_test) if len_test is not None else self.sequence_list_len
        else:
            raise ValueError(f"Invalid split: {split}")

        status = "Training" if self.training else "Testing"
        logging.info(f"{status}: OV9D normalized pose sequence count: {self.sequence_list_len}")
        logging.info(f"{status}: OV9D normalized pose dataset length: {len(self)}")

    @staticmethod
    def load_json(path: Path) -> Dict[str, Any]:
        with path.open("r", encoding="utf-8") as f:
            return json.load(f)

    @staticmethod
    def as_matrix(values, shape: Tuple[int, int]) -> np.ndarray:
        return np.asarray(values, dtype=np.float32).reshape(shape)

    @staticmethod
    def read_rgb(path: Path) -> np.ndarray:
        return np.asarray(Image.open(path).convert("RGB"), dtype=np.uint8)

    @staticmethod
    def read_depth(path: Path, depth_scale: float) -> np.ndarray:
        depth_raw = np.asarray(Image.open(path), dtype=np.float32)
        depth = depth_raw * float(depth_scale)
        depth[~np.isfinite(depth)] = 0.0
        depth[depth < 0.0] = 0.0
        return depth.astype(np.float32)

    @staticmethod
    def apply_mask_white_background(rgb: np.ndarray, mask_path: Path, threshold: int = 0) -> np.ndarray:
        mask = np.asarray(Image.open(mask_path).convert("L"), dtype=np.uint8)
        if mask.shape != rgb.shape[:2]:
            raise ValueError(f"Mask shape {mask.shape} does not match RGB shape {rgb.shape[:2]} for {mask_path}")
        keep = mask > int(threshold)
        out = np.full_like(rgb, 255, dtype=np.uint8)
        out[keep] = rgb[keep]
        return out

    @staticmethod
    def bop_camera_to_extrinsic(camera: Dict[str, Any]) -> np.ndarray:
        r_w2c = OV9DPoseNormalizeDataset.as_matrix(camera["cam_R_w2c"], (3, 3))
        t_w2c = OV9DPoseNormalizeDataset.as_matrix(camera["cam_t_w2c"], (3, 1))
        return np.concatenate([r_w2c, t_w2c], axis=1).astype(np.float32)

    @staticmethod
    def bop_camera_to_intrinsic(camera: Dict[str, Any]) -> np.ndarray:
        return OV9DPoseNormalizeDataset.as_matrix(camera["cam_K"], (3, 3)).astype(np.float32)

    @staticmethod
    def model_to_world_from_bop(camera: Dict[str, Any], gt: Dict[str, Any]) -> Tuple[np.ndarray, np.ndarray]:
        r_w2c = OV9DPoseNormalizeDataset.as_matrix(camera["cam_R_w2c"], (3, 3))
        t_w2c = OV9DPoseNormalizeDataset.as_matrix(camera["cam_t_w2c"], (3, 1)).reshape(3)
        r_m2c = OV9DPoseNormalizeDataset.as_matrix(gt["cam_R_m2c"], (3, 3))
        t_m2c = OV9DPoseNormalizeDataset.as_matrix(gt["cam_t_m2c"], (3, 1)).reshape(3)

        r_c2w = r_w2c.T
        t_c2w = -(r_c2w @ t_w2c)
        r_m2w = r_c2w @ r_m2c
        t_m2w = r_c2w @ t_m2c + t_c2w
        return r_m2w.astype(np.float32), t_m2w.astype(np.float32)

    @staticmethod
    def normalize_rotation(rotation: np.ndarray) -> np.ndarray:
        u, _, vt = np.linalg.svd(np.asarray(rotation, dtype=np.float32))
        rot = u @ vt
        if np.linalg.det(rot) < 0:
            u[:, -1] *= -1.0
            rot = u @ vt
        return rot.astype(np.float32)

    @classmethod
    def normalize_extrinsics_and_world_points(
        cls,
        extrinsics: np.ndarray,
        world_points: List[np.ndarray],
        point_masks: List[np.ndarray],
        scale_by_points: bool = True,
    ) -> Tuple[np.ndarray, float, List[np.ndarray]]:
        extrinsics = np.asarray(extrinsics, dtype=np.float32)
        seq_len = extrinsics.shape[0]
        extrinsics_homog = np.concatenate(
            [extrinsics, np.zeros((seq_len, 1, 4), dtype=np.float32)],
            axis=1,
        )
        extrinsics_homog[:, 3, 3] = 1.0

        first_cam_inv = closed_form_inverse_se3(extrinsics_homog[:1])[0]
        normalized_extrinsics = np.matmul(extrinsics_homog, first_cam_inv[None, ...])[:, :3]

        first_r = extrinsics[0, :3, :3]
        first_t = extrinsics[0, :3, 3]
        transformed_world_points = [
            (points @ first_r.T) + first_t.reshape(1, 1, 3) for points in world_points
        ]

        avg_scale = 1.0
        if scale_by_points:
            dist_sum = 0.0
            valid_count = 0.0
            for points, mask in zip(transformed_world_points, point_masks):
                dist = np.linalg.norm(points, axis=-1)
                mask_f = mask.astype(np.float32)
                dist_sum += float((dist * mask_f).sum())
                valid_count += float(mask_f.sum())
            avg_scale = float(np.clip(dist_sum / (valid_count + 1e-3), 1e-6, 1e6))
            transformed_world_points = [points / avg_scale for points in transformed_world_points]
            normalized_extrinsics[:, :3, 3] = normalized_extrinsics[:, :3, 3] / avg_scale

        return normalized_extrinsics.astype(np.float32), float(avg_scale), transformed_world_points

    @classmethod
    def normalize_object_pose_to_first_camera(
        cls,
        first_extrinsic: np.ndarray,
        object_rotation_m2w: np.ndarray,
        object_translation_m2w: np.ndarray,
        avg_scale: float,
        scale_by_points: bool = True,
    ) -> Tuple[np.ndarray, np.ndarray]:
        first_r = first_extrinsic[:3, :3]
        first_t = first_extrinsic[:3, 3]
        rotation = cls.normalize_rotation(first_r @ object_rotation_m2w)
        translation = (object_translation_m2w @ first_r.T) + first_t
        if scale_by_points:
            translation = translation / float(avg_scale)
        return rotation.astype(np.float32), translation.astype(np.float32)

    def _build_records(self) -> List[Dict[str, Any]]:
        if not self.split_json.is_file():
            raise FileNotFoundError(f"Split JSON not found: {self.split_json}")
        payload = self.load_json(self.split_json)
        scenes = payload.get("scenes", [])
        if self.debug:
            scenes = scenes[:1]

        only = set(self.only_scene_names)
        records = []
        for item in scenes:
            scene_name = str(item["scene_name"])
            if only and scene_name not in only:
                continue
            scene_dir = self.single_root / scene_name
            if self.verify_files and not self._verify_scene_files(scene_dir):
                continue
            records.append(
                {
                    "scene_name": scene_name,
                    "scene_dir": scene_dir,
                    "category": item.get("category", ""),
                    "object_instance": item.get("object_instance", ""),
                }
            )
        return records

    def _verify_scene_files(self, scene_dir: Path) -> bool:
        required = [
            scene_dir / "scene_gt.json",
            scene_dir / "scene_camera.json",
            scene_dir / "rgb",
            scene_dir / "depth",
            scene_dir / "mask_visib",
        ]
        return all(p.exists() for p in required)

    @staticmethod
    def _available_image_ids(scene_gt: Dict[str, Any]) -> List[int]:
        return sorted(int(k) for k in scene_gt.keys())

    @staticmethod
    def _ids_with_gap(ids: List[int], count: int, min_gap: int, rng: random.Random) -> Optional[List[int]]:
        if len(ids) < count:
            return None
        shuffled = list(ids)
        rng.shuffle(shuffled)
        for first in shuffled:
            selected = [first]
            candidates = [x for x in ids if x != first]
            rng.shuffle(candidates)
            for cand in candidates:
                if all(abs(cand - prev) >= min_gap for prev in selected):
                    selected.append(cand)
                    if len(selected) == count:
                        return sorted(selected)
        return None

    def _sample_image_ids(self, available_ids: List[int], count: int, rng: random.Random) -> List[int]:
        if len(available_ids) < count:
            raise ValueError(f"Need {count} views but scene only has {len(available_ids)}")
        spaced = self._ids_with_gap(available_ids, count, self.min_view_gap, rng)
        if spaced is not None:
            return spaced
        return sorted(rng.sample(available_ids, count))

    def _load_scene_view(
        self,
        scene_dir: Path,
        image_id: int,
        camera: Dict[str, Any],
    ) -> Tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
        image = self.read_rgb(scene_dir / "rgb" / f"{image_id:06d}.png")
        depth = self.read_depth(scene_dir / "depth" / f"{image_id:06d}.png", float(camera.get("depth_scale", 1.0)))
        extrinsic = self.bop_camera_to_extrinsic(camera)
        intrinsic = self.bop_camera_to_intrinsic(camera)
        world_points, cam_points, point_mask = depth_to_world_coords_points(depth, extrinsic, intrinsic)
        return (
            image,
            depth.astype(np.float32),
            extrinsic.astype(np.float32),
            intrinsic.astype(np.float32),
            world_points.astype(np.float32),
            cam_points.astype(np.float32),
            point_mask.astype(bool),
        )

    def _load_object_image(self, scene_dir: Path, image_id: int) -> np.ndarray:
        rgb = self.read_rgb(scene_dir / "rgb" / f"{image_id:06d}.png")
        mask_path = scene_dir / "mask_visib" / f"{image_id:06d}_{self.object_index:06d}.png"
        return self.apply_mask_white_background(rgb, mask_path)

    def _process_scene_view(
        self,
        image: np.ndarray,
        depth: np.ndarray,
        extrinsic: np.ndarray,
        intrinsic: np.ndarray,
        aspect_ratio: float,
        filepath: str,
    ) -> Tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
        original_size = np.array(image.shape[:2], dtype=np.int32)
        target_image_shape = self.get_target_shape(aspect_ratio)
        return self.process_one_image(
            image=image,
            depth_map=depth,
            extri_opencv=extrinsic,
            intri_opencv=intrinsic,
            original_size=original_size,
            target_image_shape=target_image_shape,
            filepath=filepath,
        )

    def _process_object_image(
        self,
        image: np.ndarray,
        aspect_ratio: float,
        filepath: str,
    ) -> np.ndarray:
        original_size = np.array(image.shape[:2], dtype=np.int32)
        target_image_shape = self.get_target_shape(aspect_ratio)
        dummy_depth = np.zeros(image.shape[:2], dtype=np.float32)
        dummy_extrinsic = np.concatenate(
            [np.eye(3, dtype=np.float32), np.zeros((3, 1), dtype=np.float32)],
            axis=1,
        )
        dummy_intrinsic = np.array(
            [
                [1.0, 0.0, image.shape[1] / 2.0],
                [0.0, 1.0, image.shape[0] / 2.0],
                [0.0, 0.0, 1.0],
            ],
            dtype=np.float32,
        )
        processed_image, *_ = self.process_one_image(
            image=image,
            depth_map=dummy_depth,
            extri_opencv=dummy_extrinsic,
            intri_opencv=dummy_intrinsic,
            original_size=original_size,
            target_image_shape=target_image_shape,
            filepath=filepath,
        )
        return processed_image

    def _sample_negative_record(self, current_scene_name: str, rng: random.Random) -> Optional[Dict[str, Any]]:
        candidates = [rec for rec in self.records if rec["scene_name"] != current_scene_name]
        if not candidates:
            return None
        return rng.choice(candidates)

    def get_data(
        self,
        seq_index: int = None,
        img_per_seq: int = None,
        seq_name: str = None,
        ids: list = None,
        aspect_ratio: float = 1.0,
    ) -> dict:
        del seq_name, ids

        if self.inside_random and self.training:
            seq_index = random.randint(0, self.sequence_list_len - 1)
        if seq_index is None:
            seq_index = 0

        rec = self.records[seq_index % self.sequence_list_len]
        scene_dir: Path = rec["scene_dir"]
        scene_name = rec["scene_name"]
        scene_gt = self.load_json(scene_dir / "scene_gt.json")
        scene_camera = self.load_json(scene_dir / "scene_camera.json")
        available_ids = self._available_image_ids(scene_gt)

        frame_num = int(img_per_seq) if img_per_seq is not None else self.num_scene_views
        frame_num = max(1, min(frame_num, len(available_ids)))
        scene_ids = self._sample_image_ids(available_ids, frame_num, random)

        use_negative_object = (
            self.negative_object_prob > 0.0
            and random.random() < self.negative_object_prob
        )
        object_rec = rec
        if use_negative_object:
            negative_rec = self._sample_negative_record(scene_name, random)
            if negative_rec is not None:
                object_rec = negative_rec
            else:
                use_negative_object = False

        object_scene_dir: Path = object_rec["scene_dir"]
        object_scene_gt = scene_gt if object_scene_dir == scene_dir else self.load_json(object_scene_dir / "scene_gt.json")
        object_available_ids = self._available_image_ids(object_scene_gt)
        object_ids = self._sample_image_ids(object_available_ids, self.num_object_views, random)

        scene_images = []
        raw_depths = []
        raw_cam_points = []
        raw_world_points = []
        point_masks = []
        extrinsics = []
        intrinsics = []
        original_sizes = []
        for image_id in scene_ids:
            image, depth, extrinsic, intrinsic, world_points, cam_points, point_mask = self._load_scene_view(
                scene_dir,
                image_id,
                scene_camera[str(image_id)],
            )
            image, depth, extrinsic, intrinsic, world_points, cam_points, point_mask, _ = self._process_scene_view(
                image=image,
                depth=depth,
                extrinsic=extrinsic,
                intrinsic=intrinsic,
                aspect_ratio=aspect_ratio,
                filepath=str(scene_dir / "rgb" / f"{image_id:06d}.png"),
            )
            scene_images.append(image)
            raw_depths.append(depth)
            raw_cam_points.append(cam_points)
            raw_world_points.append(world_points)
            point_masks.append(point_mask)
            extrinsics.append(extrinsic)
            intrinsics.append(intrinsic)
            original_sizes.append(np.array(image.shape[:2], dtype=np.int32))

        extrinsics_np = np.stack(extrinsics).astype(np.float32)
        normalized_extrinsics, avg_scale, normalized_world_points = self.normalize_extrinsics_and_world_points(
            extrinsics=extrinsics_np,
            world_points=raw_world_points,
            point_masks=point_masks,
            scale_by_points=self.scale_by_points,
        )

        first_id = scene_ids[0]
        first_camera = scene_camera[str(first_id)]
        first_gt = scene_gt[str(first_id)][self.object_index]
        object_rotation_m2w, object_translation_m2w = self.model_to_world_from_bop(first_camera, first_gt)
        normalized_object_rotation, normalized_object_translation = self.normalize_object_pose_to_first_camera(
            first_extrinsic=extrinsics_np[0],
            object_rotation_m2w=object_rotation_m2w,
            object_translation_m2w=object_translation_m2w,
            avg_scale=avg_scale,
            scale_by_points=self.scale_by_points,
        )

        object_images = []
        object_original_sizes = []
        for image_id in object_ids:
            object_image = self._load_object_image(object_scene_dir, image_id)
            object_image = self._process_object_image(
                image=object_image,
                aspect_ratio=aspect_ratio,
                filepath=str(object_scene_dir / "rgb" / f"{image_id:06d}.png"),
            )
            object_images.append(object_image)
            object_original_sizes.append(np.array(object_image.shape[:2], dtype=np.int32))

        batch = {
            "seq_name": f"ov9d_pose_normalize_{self.split}/{scene_name}",
            "ids": np.array(scene_ids, dtype=np.int64),
            "frame_num": len(scene_ids),
            "images": scene_images,
            "object_images": object_images,
            "extrinsics": normalized_extrinsics,
            "intrinsics": intrinsics,
            "original_sizes": original_sizes,
            "object_original_sizes": object_original_sizes,
            "camera_indices": np.array(scene_ids, dtype=np.int64),
            "object_cam_indices": np.array(object_ids, dtype=np.int64),
            "object_name": rec.get("object_instance") or scene_name,
            "object_reference_name": object_rec.get("object_instance") or object_rec["scene_name"],
            "category": rec.get("category", ""),
            "object_reference_category": object_rec.get("category", ""),
            "scene_name": scene_name,
            "run_name": scene_name,
            "skip_normalization": True,
            "has_object": np.array(0.0 if use_negative_object else 1.0, dtype=np.float32),
            "object_rotation": normalized_object_rotation,
            "object_translation": normalized_object_translation,
            "object_srt": np.concatenate(
                [normalized_object_rotation.reshape(-1), normalized_object_translation], axis=0
            ).astype(np.float32),
            "normalization_scale": np.array([avg_scale], dtype=np.float32),
        }

        if self.load_point_map:
            scale = avg_scale if self.scale_by_points else 1.0
            batch.update(
                {
                    "depths": [(depth / scale).astype(np.float32) for depth in raw_depths],
                    "cam_points": [(points / scale).astype(np.float32) for points in raw_cam_points],
                    "world_points": [points.astype(np.float32) for points in normalized_world_points],
                    "point_masks": point_masks,
                    "object_masks": point_masks,
                }
            )

        return batch
